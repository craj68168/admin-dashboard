type NotificationType = ReturnType<typeof useNotificationStore.getState>["type"];

const normalizeMessage = (message: string) =>
  message.trim().replace(/\s+/g, " ").replace(/[.!]+$/, "").toLowerCase();

const messageKeys = new Map(
  Object.entries(messages.en).filter(([, message]) => !message.includes("{")).map(([key, message]) => [
    normalizeMessage(message),
    key as keyof typeof messages.en,
  ]),
);

function translateNotification(
  message: string,
  locale: string,
  type: NotificationType,
) {
  const t = createTranslator({
    locale,
    messages: messages[locale === "ja" ? "ja" : "en"],
  });
  const fallbackKey = {
    error: "fallbackError",
    success: "fallbackSuccess",
    warning: "fallbackWarning",
    info: "fallbackInfo",
  } as const;

  if (typeof message !== "string") return t(fallbackKey[type]);
  const text = message.trim();
  if (!text) return "";

  const key = messageKeys.get(normalizeMessage(text));
  if (key) return t(key);

  // Match complete server messages so IDs, amounts, and counts remain data.
  let match = /^Staff (.+) not found\.?$/i.exec(text);
  if (match) return t("staffNotFoundById", { id: match[1] });

  match = /^Expected amount cannot be less than the already paid amount of (.+?)\.?$/i.exec(text);
  if (match) return t("minimumExpectedAmount", { amount: match[1] });

  match = /^This stage cannot be deleted because (\d+) client\(s\) currently use it\. Deactivate it instead\.?$/i.exec(text);
  if (match) return t("stageInUse", { count: Number(match[1]) });

  match = /^Invalid or unexpected file: (.+)$/i.exec(text);
  if (match) return t("unexpectedFile", { field: match[1] });

  match = /^¥(.+?) registration payment confirmed and client created\.?$/i.exec(text);
  if (match) return t("registrationPaymentConfirmed", { amount: match[1] });

  match = /^Payment of ¥(.+?) completed and stage updated\.?$/i.exec(text);
  if (match) return t("stagePaymentCompleted", { amount: match[1] });

  match = /^(\w+) must (be an array|contain a valid JSON array|contain valid JSON)\.?$/i.exec(text);
  if (match) {
    const fieldKeys = {
      education: "fieldEducation",
      employmentHistory: "fieldEmploymentHistory",
      qualifications: "fieldQualifications",
      skills: "fieldSkills",
    } as const;
    const fieldKey = fieldKeys[match[1] as keyof typeof fieldKeys];
    const field = fieldKey ? t(fieldKey) : t("fieldSubmittedData");
    return t(match[2].toLowerCase() === "be an array" ? "arrayRequired" : "validJsonRequired", { field });
  }

  match = /^Request failed with status code (\d+)$/i.exec(text);
  if (match) return t("httpError", { status: match[1] });

  match = /^timeout of (\d+)ms exceeded$/i.exec(text);
  if (match) return t("requestTimeout", { duration: match[1] });

  // Preserve English diagnostics and already localized Japanese notifications.
  if (locale !== "ja" || /^[\u3040-\u30ff\u3400-\u9fff]/u.test(text)) return text;
  if (/validation failed|cast to .+ failed/i.test(text)) return t("validationError");
  if (/E11000|duplicate key/i.test(text)) return t("duplicateDataExists");

  // Unexpected server/library errors still receive a localized notification.
  return t(fallbackKey[type]);
}

export default function GlobalSnackbar() {
  const locale = useLocale();
  const open = useNotificationStore((state) => state.open);
  const message = useNotificationStore((state) => state.message);
  const type = useNotificationStore((state) => state.type);
  const closeNotification = useNotificationStore(
    (state) => state.closeNotification,
  );

  return (
    <Snackbar
      open={open}
      autoHideDuration={4000}
      onClose={closeNotification}
      anchorOrigin={{
        vertical: "top",
        horizontal: "right",
      }}
    >
      <Alert
        onClose={closeNotification}
        closeText={translateNotification(messages.en.close, locale, "info")}
        severity={type}
        variant="filled"
        sx={{ width: "100%" }}
      >
        {translateNotification(message, locale, type)}
      </Alert>
    </Snackbar>
  );
}
